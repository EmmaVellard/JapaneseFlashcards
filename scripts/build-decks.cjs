// Rebuild the browser decks from a pinned, attributed dictionary snapshot.
// Local corrections and progress aliases live in data/curation.json.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = (name) =>
  JSON.parse(fs.readFileSync(path.join(root, 'data', name), 'utf8'));
const reference = read('openjlpt-n5-n4.json');
const curation = read('curation.json');
const examples = read('examples.json').cards;
const slug = (text) => encodeURIComponent(text).replace(/%/g, '').toLowerCase();
const unique = (values) => [...new Set(values.filter(Boolean))];

function describePartsOfSpeech(codes, word) {
  const labels = [];
  for (const code of codes) {
    if (/^n($|-)/.test(code) && !word.endsWith('する')) labels.push('noun');
    if (code === 'pn') labels.push('pronoun');
    if (code === 'adj-i' || code === 'adj-ix') labels.push('i-adjective');
    if (code === 'adj-na') labels.push('na-adjective');
    if (code === 'adj-no') labels.push('no-adjective');
    if (code === 'adj-pn' || code === 'adj-f')
      labels.push('pre-noun adjective');
    if (/^adv/.test(code)) labels.push('adverb');
    if (code === 'exp' || code === 'int') labels.push('expression');
    if (code === 'conj') labels.push('conjunction');
    if (code === 'prt') labels.push('particle');
    if (code === 'ctr') labels.push('counter');
    if (code === 'num') labels.push('numeral');
    if (code === 'pref' || code === 'n-pref') labels.push('prefix');
    if (code === 'suf' || code === 'n-suf') labels.push('suffix');
    if (code.startsWith('vs')) labels.push('suru verb');
    else if (/^v[1-5]|^v[k-z]/.test(code)) labels.push('verb');
    if (code === 'vt') labels.push('transitive');
    if (code === 'vi') labels.push('intransitive');
    if (/^aux/.test(code)) labels.push('auxiliary');
  }
  return unique(labels).join(', ') || 'expression';
}

function legacyIds(id) {
  const ids = curation.legacyIds[id];
  return ids ? { legacyIds: unique(ids) } : {};
}

const kanji = reference.kanji.map((entry) => {
  const id = `kanji-${slug(entry.character)}`;
  assert.equal(
    Array.from(entry.character).length,
    1,
    'A kanji card contains exactly one character'
  );
  return {
    id,
    kanji: entry.character,
    level: entry.level,
    meaning: entry.meanings.join('; '),
    onyomi: entry.onyomi.join(', ') || '—',
    kunyomi: entry.kunyomi.join(', ') || '—',
    example: examples[id],
    ...legacyIds(id)
  };
});

const vocabulary = reference.vocabulary.map((original) => {
  const edits = curation.corrections.filter(
    (fix) => fix.word === original.word && fix.reading === original.reading
  );
  const entry = Object.assign({}, original, ...edits.map((fix) => fix.set));
  const id = `openjlpt-${original.id}`;
  const otherForms = unique([
    ...(entry.other_forms || []),
    original.word
  ]).filter((word) => word !== entry.word);
  const otherReadings = unique([
    ...(entry.other_readings || []),
    original.reading
  ]).filter((reading) => reading !== entry.reading);
  return {
    id,
    word: entry.word,
    reading: entry.reading,
    level: entry.level,
    meaning: entry.meanings.join('; '),
    type: describePartsOfSpeech(entry.pos, entry.word),
    example: examples[id],
    ...(otherForms.length ? { otherForms } : {}),
    ...(otherReadings.length ? { otherReadings } : {}),
    ...(entry.jmdict_id ? { jmdictId: entry.jmdict_id } : {}),
    ...legacyIds(id)
  };
});
for (const entry of curation.supplementaryVocabulary) {
  const id = `supplement-${slug(entry.word)}-${slug(entry.reading)}`;
  vocabulary.push({ id, ...entry, example: examples[id], ...legacyIds(id) });
}

// A source may contain homographs with different readings. Keep those cards.
for (const [kind, entries] of [
  ['kanji', kanji],
  ['vocabulary', vocabulary]
]) {
  assert.equal(
    new Set(entries.map((entry) => entry.id)).size,
    entries.length,
    `Duplicate ${kind} IDs`
  );
  for (const entry of entries) {
    assert.ok(entry.meaning.trim());
    assert.ok(
      entry.example?.ja && entry.example?.en,
      `Missing example for ${entry.id}`
    );
    assert.ok(entry.level === 'N5' || entry.level === 'N4');
  }
}
for (const level of ['N5', 'N4']) {
  for (const [kind, entries, variable] of [
    ['kanji', kanji, level === 'N5' ? 'kanjiList' : 'kanjiN4List'],
    ['vocab', vocabulary, level === 'N5' ? 'vocabN5List' : 'vocabN4List']
  ]) {
    const rows = entries.filter((entry) => entry.level === level);
    const text =
      '// Generated by npm run build:decks. See data/README.md for sources and corrections.\n' +
      '// Data: CC BY-SA 4.0; OpenJLPT, EDRDG, Jonathan Waller; Tatoeba examples: CC BY 2.0 FR.\n' +
      `const ${variable} = [\n${rows.map((row) => '  ' + JSON.stringify(row)).join(',\n')}\n];\n`;
    fs.writeFileSync(path.join(root, 'Lists', `${kind}${level}.js`), text);
    console.log(`${kind} ${level}: ${rows.length}`);
  }
}
